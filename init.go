// компоненты для работы с реляционными базами данных в Go.
//
// Основные возможности:
//   - Универсальные компоненты для CRUD операций: Finder, Saver, Deleter и др.
//   - Типобезопасные фильтры и сортировка с поддержкой распространённых операторов.
//   - Поддержка пагинации через компонент Pager.
//   - Гибкое преобразование между моделями и SQL-записями через функции-мапперы.
//
// Все компоненты используют стандартный интерфейс dbClient.Client,
// что упрощает тестирование и позволяет легко подменять реализацию хранения данных.
